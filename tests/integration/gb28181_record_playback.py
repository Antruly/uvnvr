#!/usr/bin/env python3
"""Platform-side GB/T 28181 RecordInfo and playback check (GH-19).

The script plays the role of a minimal platform:

  * answers the device REGISTER without authentication;
  * sends a RecordInfo MESSAGE and validates the returned index;
  * sends an INVITE with s=Playback and u=<channel>:<start>:<end>;
  * receives RTP/PS, checks the PS pack header and decodes it with ffprobe;
  * sends SIP INFO Scale=2, Scale=0 (pause), Scale=1 and a Range seek, then
    measures the RTP timestamp rate and the packet gap while paused;
  * sends BYE.

It starts the real uvnvr binary against a temporary data directory. The
database is created by one short run, then a channel and one recording row are
inserted with Python's sqlite3 and a 30-second H.264 MPEG-TS file generated by
ffmpeg.

Usage:
  tests/integration/gb28181_record_playback.py [--binary build-gb/uvnvr]
                                                [--ffmpeg ...]
                                                [--keep]

Exit status is non-zero on the first failed assertion. All evidence is printed
to stdout so it can be quoted in the PR.
"""

import argparse
import datetime
import os
import random
import shutil
import signal
import socket
import sqlite3
import subprocess
import sys
import tempfile
import time
import urllib.request

DEVICE_ID = "34020000001180000001"
CHANNEL_ID = "34020000001320000001"
CENTER_CODE = "34020000"
SIP_PORT = 15060
DEVICE_SIP_PORT = 15061
RTP_PORT = 41000
HTTP_PORT = 18080
RTSP_PORT = 18554
PRIVATE_PORT = 11515

CHANNEL_LOCAL_ID = 1
RECORD_START = datetime.datetime(2026, 11, 25, 12, 0, 0)
RECORD_SECONDS = 30


def epoch_ms(dt):
    return int(time.mktime(dt.timetuple())) * 1000


def compact(dt):
    return dt.strftime("%Y%m%d%H%M%S")


def iso(dt):
    return dt.strftime("%Y-%m-%dT%H:%M:%S")


class CheckFailed(Exception):
    pass


def check(condition, message):
    if not condition:
        raise CheckFailed(message)
    print("OK:", message)


def http_ok(port):
    try:
        with urllib.request.urlopen(f"http://127.0.0.1:{port}/healthz", timeout=0.5) as resp:
            return resp.status == 200
    except Exception:
        return False


def parse_sip(data):
    if b"\r\n\r\n" in data:
        head, body = data.split(b"\r\n\r\n", 1)
    else:
        head, body = data, b""
    text = head.decode("utf-8", "replace")
    lines = text.replace("\r\n", "\n").split("\n")
    first = lines[0] if lines else ""
    headers = []
    for line in lines[1:]:
        if ":" in line:
            name, value = line.split(":", 1)
            headers.append((name.strip(), value.strip()))
    return first, headers, body.decode("utf-8", "replace")


def header(headers, name):
    for key, value in headers:
        if key.lower() == name.lower():
            return value
    return ""


def headers_all(headers, name):
    return [value for key, value in headers if key.lower() == name.lower()]


def sip_response(data, code, reason, extra=None):
    first, headers, _ = parse_sip(data)
    del first
    to = header(headers, "To")
    if ";tag=" not in to:
        to += ";tag=fakeplatform%d" % random.randint(1000, 9999)
    lines = [f"SIP/2.0 {code} {reason}"]
    lines.extend(f"Via: {via}" for via in headers_all(headers, "Via"))
    lines.append(f"From: {header(headers, 'From')}")
    lines.append(f"To: {to}")
    lines.append(f"Call-ID: {header(headers, 'Call-ID')}")
    lines.append(f"CSeq: {header(headers, 'CSeq')}")
    lines.append("User-Agent: uvnvr-gb28181-integration")
    for name, value in extra or []:
        lines.append(f"{name}: {value}")
    lines.append("Content-Length: 0")
    return ("\r\n".join(lines) + "\r\n\r\n").encode()


def sip_request(method, target, call_id, cseq, body="", content_type=None, from_tag="plat"):
    branch = "z9hG4bK%08x" % random.getrandbits(32)
    lines = [
        f"{method} sip:{target}@127.0.0.1 SIP/2.0",
        f"Via: SIP/2.0/UDP 127.0.0.1:{SIP_PORT};branch={branch};rport",
        "Max-Forwards: 70",
        f"From: <sip:platform@127.0.0.1:{SIP_PORT}>;tag={from_tag}",
        f"To: <sip:{target}@127.0.0.1>",
        f"Call-ID: {call_id}",
        f"CSeq: {cseq} {method}",
        f"Contact: <sip:platform@127.0.0.1:{SIP_PORT}>",
        "User-Agent: uvnvr-gb28181-integration",
    ]
    if content_type:
        lines.append(f"Content-Type: {content_type}")
    payload = body.encode("utf-8")
    lines.append(f"Content-Length: {len(payload)}")
    return ("\r\n".join(lines) + "\r\n\r\n").encode() + payload


def parse_rtp(packet):
    if len(packet) < 13:
        return None
    if (packet[0] >> 6) != 2:
        return None
    payload_type = packet[1] & 0x7F
    sequence = int.from_bytes(packet[2:4], "big")
    timestamp = int.from_bytes(packet[4:8], "big")
    ssrc = int.from_bytes(packet[8:12], "big")
    return {
        "pt": payload_type,
        "seq": sequence,
        "ts": timestamp,
        "ssrc": ssrc,
        "payload": packet[12:],
        "at": time.monotonic(),
    }


def sdp_answer_value(sdp, prefix):
    for line in sdp.replace("\r\n", "\n").split("\n"):
        if line.startswith(prefix):
            return line[len(prefix):].strip()
    return ""


def wait_health(proc, port, timeout=20.0):
    deadline = time.time() + timeout
    while time.time() < deadline:
        if proc.poll() is not None:
            raise CheckFailed(f"uvnvr exited during startup with {proc.returncode}")
        if http_ok(port):
            return
        time.sleep(0.2)
    raise CheckFailed("uvnvr did not become healthy")


def first_run(binary, data_dir):
    proc = subprocess.Popen(
        [binary, "--data-dir", data_dir, "--port", str(HTTP_PORT),
         "--rtsp-port", str(RTSP_PORT), "--private-port", str(PRIVATE_PORT),
         "--log-level", "warn"],
        stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    try:
        wait_health(proc, HTTP_PORT)
    finally:
        proc.send_signal(signal.SIGKILL)
        proc.wait(timeout=5)
    print("database: schema initialised at", os.path.join(data_dir, "uvnvr.db"))


def prepare_database(data_dir, media_path):
    db_path = os.path.join(data_dir, "uvnvr.db")
    start_ms = epoch_ms(RECORD_START)
    end_ms = start_ms + RECORD_SECONDS * 1000
    size = os.path.getsize(media_path)
    db = sqlite3.connect(db_path)
    try:
        db.execute(
            "INSERT OR REPLACE INTO channels(id,name,protocol,host,port,username,password_enc,"
            "main_url,sub_url,sub_enabled,enabled,brand,media_json,watermark_json,last_status,"
            "last_error,last_online_at,last_offline_at,created_at,updated_at) "
            "VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)",
            (CHANNEL_LOCAL_ID, "gate", "rtsp", "127.0.0.1", 554, "", "", "", "", 0, 1, "",
             "{}", "{}", "unknown", "", 0, 0, 0, 0))
        db.execute(
            "INSERT INTO recordings(channel_id,stream,volume_id,path,start_ms,end_ms,"
            "duration_ms,size_bytes,codec,record_type,created_at) VALUES(?,?,?,?,?,?,?,?,?,?,?)",
            (CHANNEL_LOCAL_ID, "main", 1, media_path, start_ms, end_ms,
             RECORD_SECONDS * 1000, size, "h264", "timed", 0))
        settings = {
            "gb28181.enabled": "1",
            "gb28181.device_id": DEVICE_ID,
            "gb28181.name": "UvNVR-integration",
            "gb28181.center_code": CENTER_CODE,
            "gb28181.server_host": "127.0.0.1",
            "gb28181.server_port": str(SIP_PORT),
            "gb28181.transport": "udp",
            "gb28181.local_ip": "127.0.0.1",
            "gb28181.bind_ip": "127.0.0.1",
            "gb28181.local_port": str(DEVICE_SIP_PORT),
            "gb28181.username": DEVICE_ID,
            "gb28181.password": "",
            "gb28181.stream": "main",
            "gb28181.playback_burst_ms": "0",
            "gb28181.rtp_port_min": str(RTP_PORT),
            "gb28181.rtp_port_max": str(RTP_PORT + 20),
            "gb28181.max_sessions": "4",
        }
        for key, value in settings.items():
            db.execute("INSERT OR REPLACE INTO settings(key,value,updated_at) VALUES(?,?,?)",
                       (key, value, int(time.time())))
        db.commit()
        row = db.execute("SELECT path,start_ms,end_ms,size_bytes FROM recordings").fetchone()
        print("recording row:", row)
    finally:
        db.close()


class Platform:
    def __init__(self, device_id, channel_id):
        self.device_id = device_id
        self.channel_id = channel_id
        self.sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        self.sock.bind(("127.0.0.1", SIP_PORT))
        self.sock.settimeout(5.0)
        self.device_addr = None
        self.rtp = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        self.rtp.bind(("127.0.0.1", RTP_PORT))
        self.rtp.settimeout(0.2)

    def close(self):
        self.sock.close()
        self.rtp.close()

    def recv(self, timeout=5.0):
        self.sock.settimeout(timeout)
        data, addr = self.sock.recvfrom(65535)
        self.device_addr = addr
        return data, addr

    def wait_register(self, timeout=10.0):
        deadline = time.time() + timeout
        while time.time() < deadline:
            data, addr = self.recv(deadline - time.time())
            first, _, _ = parse_sip(data)
            if first.startswith("REGISTER "):
                self.device_addr = addr
                self.sock.sendto(sip_response(data, 200, "OK"), addr)
                print("platform: REGISTER -> 200 OK from", addr)
                return
        raise CheckFailed("no REGISTER from the device")

    def send(self, data):
        self.sock.sendto(data, self.device_addr)

    def wait_response(self, call_id, method=None, timeout=8.0):
        deadline = time.time() + timeout
        while time.time() < deadline:
            data, _ = self.recv(max(0.1, deadline - time.time()))
            first, headers, body = parse_sip(data)
            if first.startswith("REGISTER "):
                self.sock.sendto(sip_response(data, 200, "OK"), self.device_addr)
                continue
            if first.startswith("SIP/2.0 "):
                if header(headers, "Call-ID") != call_id:
                    continue
                if method and not header(headers, "CSeq").upper().endswith(method.upper()):
                    continue
                return int(first.split()[1]), headers, body
            if first.startswith("MESSAGE ") and call_id == "recordinfo":
                self.sock.sendto(sip_response(data, 200, "OK"), self.device_addr)
                return 0, headers, body
        raise CheckFailed(f"no SIP response for {call_id} {method}")

    def query_record_info(self, start, end):
        body = (
            "<?xml version=\"1.0\" encoding=\"GB2312\"?>\r\n"
            "<Query>\r\n"
            "  <CmdType>RecordInfo</CmdType>\r\n"
            "  <SN>100</SN>\r\n"
            f"  <DeviceID>{self.channel_id}</DeviceID>\r\n"
            f"  <StartTime>{iso(start)}</StartTime>\r\n"
            f"  <EndTime>{iso(end)}</EndTime>\r\n"
            "  <Secrecy>0</Secrecy>\r\n"
            "  <Type>all</Type>\r\n"
            "</Query>\r\n")
        call_id = "recordinfo"
        req = sip_request("MESSAGE", self.device_id, call_id, 10, body,
                          "Application/MANSCDP+xml")
        self.send(req)
        # The device answers 200 to the MESSAGE and sends the Response in a
        # separate MESSAGE request (call_id is not the transaction id).
        deadline = time.time() + 8.0
        while time.time() < deadline:
            data, _ = self.recv(max(0.1, deadline - time.time()))
            first, headers, response_body = parse_sip(data)
            if first.startswith("SIP/2.0 "):
                continue
            if first.startswith("MESSAGE "):
                self.sock.sendto(sip_response(data, 200, "OK"), self.device_addr)
                if "RecordInfo" in response_body:
                    return response_body
            if first.startswith("REGISTER "):
                self.sock.sendto(sip_response(data, 200, "OK"), self.device_addr)
        raise CheckFailed("no RecordInfo response MESSAGE")

    def invite_playback(self, call_id, start, end):
        body = (
            "v=0\r\n"
            f"o={self.channel_id} 0 0 IN IP4 127.0.0.1\r\n"
            "s=Playback\r\n"
            f"u={self.channel_id}:{compact(start)}:{compact(end)}\r\n"
            "c=IN IP4 127.0.0.1\r\n"
            "t=0 0\r\n"
            f"m=video {RTP_PORT} RTP/AVP 96\r\n"
            "a=recvonly\r\n"
            "a=rtpmap:96 PS/90000\r\n"
            "y=01020304\r\n")
        req = sip_request("INVITE", self.channel_id, call_id, 20, body, "application/sdp")
        self.send(req)
        code, headers, answer = self.wait_response(call_id, "INVITE")
        if code != 200:
            raise CheckFailed(f"INVITE answered {code}: {answer}")
        ack = sip_request("ACK", self.channel_id, call_id, 20)
        self.send(ack)
        return headers, answer

    def info(self, call_id, scale=None, range_start=None, range_end=None, cseq=30):
        fields = ["<Control>", "<CmdType>Playback</CmdType>", "<SN>%d</SN>" % cseq,
                  f"<DeviceID>{self.channel_id}</DeviceID>"]
        if scale is not None:
            fields.append(f"<Scale>{scale:.2f}</Scale>")
        if range_start is not None and range_end is not None:
            fields.append(f"<Range>{iso(range_start)}/{iso(range_end)}</Range>")
        fields.append("</Control>")
        body = "<?xml version=\"1.0\" encoding=\"GB2312\"?>\r\n" + "\r\n".join(fields) + "\r\n"
        self.send(sip_request("INFO", self.channel_id, call_id, cseq, body,
                              "Application/MANSCDP+xml"))
        code, _, _ = self.wait_response(call_id, "INFO")
        if code != 200:
            raise CheckFailed(f"INFO answered {code}")

    def collect_rtp(self, duration):
        packets = []
        deadline = time.monotonic() + duration
        while True:
            remaining = deadline - time.monotonic()
            if remaining <= 0:
                break
            self.rtp.settimeout(remaining)
            try:
                data, _ = self.rtp.recvfrom(65535)
            except socket.timeout:
                break
            packet = parse_rtp(data)
            if packet and packet["pt"] == 96:
                packets.append(packet)
        return packets

    def bye(self, call_id, cseq=40):
        self.send(sip_request("BYE", self.channel_id, call_id, cseq))
        try:
            code, _, _ = self.wait_response(call_id, "BYE", timeout=3.0)
            print("platform: BYE answered", code)
        except CheckFailed:
            print("platform: BYE was not answered (the dialog may already be closed)")


def run(args):
    data_dir = tempfile.mkdtemp(prefix="uvnvr-gb28181-")
    media_dir = os.path.join(data_dir, "recordings", "2026", "11", "25")
    os.makedirs(media_dir, exist_ok=True)
    media_path = os.path.join(media_dir, "gate.ts")
    print("data dir:", data_dir)
    subprocess.run(
        [args.ffmpeg, "-hide_banner", "-loglevel", "error", "-y",
         "-f", "lavfi", "-i", "testsrc=size=320x240:rate=25",
         "-t", str(RECORD_SECONDS), "-c:v", "libx264", "-preset", "ultrafast",
         "-g", "25", "-pix_fmt", "yuv420p", "-f", "mpegts", media_path],
        check=True)
    print("fixture:", media_path, os.path.getsize(media_path), "bytes")

    first_run(args.binary, data_dir)
    prepare_database(data_dir, media_path)

    platform = Platform(DEVICE_ID, CHANNEL_ID)
    log_path = os.path.join(data_dir, "uvnvr.log")
    log_file = open(log_path, "w")
    proc = subprocess.Popen(
        [args.binary, "--data-dir", data_dir, "--port", str(HTTP_PORT),
         "--rtsp-port", str(RTSP_PORT), "--private-port", str(PRIVATE_PORT),
         "--log-level", "debug"],
        stdout=log_file, stderr=subprocess.STDOUT, text=True)
    try:
        wait_health(proc, HTTP_PORT)
        platform.wait_register()

        start = RECORD_START
        end = start + datetime.timedelta(seconds=60)
        xml = platform.query_record_info(start - datetime.timedelta(seconds=60),
                                         end + datetime.timedelta(seconds=60))
        check("<CmdType>RecordInfo</CmdType>" in xml, "RecordInfo response carries CmdType")
        check("<SumNum>1</SumNum>" in xml, "RecordInfo response reports one recording")
        check("<DeviceID>%s</DeviceID>" % CHANNEL_ID in xml,
              "RecordInfo item uses the channel's 20-digit identifier")
        check("<Type>time</Type>" in xml, "timed recording is reported as Type=time")
        print("RecordInfo response:\n" + xml.strip())

        call_id = "playback-%d" % random.getrandbits(32)
        _, answer = platform.invite_playback(call_id, start,
                                             start + datetime.timedelta(seconds=40))
        media_port = sdp_answer_value(answer, "m=video ")
        check(media_port.startswith(str(RTP_PORT)) or media_port,
              "INVITE answered with an SDP video section: " + media_port)
        ssrc_line = sdp_answer_value(answer, "y=")
        check(len(ssrc_line) >= 4, "INVITE answer carries an SSRC in y=")
        print("INVITE answer:\n" + answer.strip())

        packets = platform.collect_rtp(1.2)
        check(len(packets) > 10, "RTP/PS packets arrive after ACK (%d)" % len(packets))
        check(packets[0]["payload"][:4] == b"\x00\x00\x01\xba",
              "RTP payload starts with a PS pack header 00 00 01 BA")
        check(packets[0]["ssrc"] == int(ssrc_line), "RTP SSRC matches the SDP y= value")

        ps_capture = os.path.join(data_dir, "capture.ps")
        with open(ps_capture, "wb") as capture:
            for packet in packets:
                capture.write(packet["payload"])
        ffprobe = args.ffprobe or "ffprobe"
        probe = subprocess.run(
            [ffprobe, "-v", "error", "-select_streams", "v:0",
             "-show_entries", "stream=codec_name,width,height", "-of", "default=nw=1",
             ps_capture],
            capture_output=True, text=True)
        check(probe.returncode == 0 and "codec_name=h264" in probe.stdout,
              "captured PS decodes as H.264: " + probe.stdout.strip().replace("\n", " "))

        platform.info(call_id, scale=2.0, cseq=31)
        time.sleep(0.3)
        fast = platform.collect_rtp(2.0)
        check(len(fast) >= 20, "playback continues at 2x (%d packets)" % len(fast))
        fast_rate = (fast[-1]["ts"] - fast[0]["ts"]) / 90000.0 / (fast[-1]["at"] - fast[0]["at"])
        check(1.4 <= fast_rate <= 2.8, "2x scale measured at %.2fx" % fast_rate)
        print("speed: Scale=2.00 -> %.2fx RTP timestamp rate" % fast_rate)

        platform.info(call_id, scale=0.0, cseq=32)
        time.sleep(0.4)
        paused = platform.collect_rtp(1.0)
        check(len(paused) <= 2, "Scale=0 pauses the stream (%d packets in 1 s)" % len(paused))
        print("pause: Scale=0.00 -> %d packets in 1.0 s" % len(paused))

        platform.info(call_id, scale=1.0, cseq=33)
        time.sleep(0.4)
        resumed = platform.collect_rtp(1.2)
        check(len(resumed) >= 10, "Scale=1 resumes the stream (%d packets)" % len(resumed))
        print("resume: Scale=1.00 -> %d packets" % len(resumed))

        seek_start = start + datetime.timedelta(seconds=20)
        seek_end = start + datetime.timedelta(seconds=35)
        platform.info(call_id, range_start=seek_start, range_end=seek_end, cseq=34)
        after_seek = platform.collect_rtp(1.5)
        check(len(after_seek) >= 10, "Range seek keeps the stream alive (%d packets)" %
              len(after_seek))
        check(after_seek[0]["ts"] < resumed[-1]["ts"],
              "seek restarts the RTP timeline (new timestamp %d < %d)" %
              (after_seek[0]["ts"], resumed[-1]["ts"]))
        print("seek: Range %s/%s -> RTP timestamp reset to %d" %
              (iso(seek_start), iso(seek_end), after_seek[0]["ts"]))

        platform.bye(call_id)
        print("PASS: RecordInfo and playback (speed/pause/seek) verified against the SIP platform")
    except CheckFailed:
        log_file.flush()
        with open(log_path, "r", errors="replace") as log:
            print("--- uvnvr log tail ---")
            print("".join(log.readlines()[-80:]))
        raise
    finally:
        proc.send_signal(signal.SIGKILL)
        try:
            proc.wait(timeout=5)
        except subprocess.TimeoutExpired:
            pass
        log_file.close()
        platform.close()
        if not args.keep:
            shutil.rmtree(data_dir, ignore_errors=True)
        else:
            print("kept data dir:", data_dir)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--binary", default=os.environ.get("UVNVR_BINARY", "build-gb/uvnvr"))
    parser.add_argument("--ffmpeg", default=os.environ.get("FFMPEG", "ffmpeg"))
    parser.add_argument("--ffprobe", default=os.environ.get("FFPROBE", "ffprobe"))
    parser.add_argument("--keep", action="store_true")
    args = parser.parse_args()
    if not os.path.exists(args.binary):
        print("binary not found:", args.binary, file=sys.stderr)
        return 2
    try:
        run(args)
    except CheckFailed as error:
        print("FAIL:", error, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
